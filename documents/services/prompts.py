"""Версионированные промпты для GigaChat.

Каждый промпт хранится по версиям. Когда меняешь текст промпта —
поднимай номер версии. Версия попадает в processing_meta, и по ней
можно сравнивать результаты оценки.

ВАЖНО: этот файл — единственный источник текста промптов.
Не вставляй промпты прямо в llm.py или pipeline.py.
"""

from __future__ import annotations


# --- Классификация типа документа ------------------------------------------

CLASSIFY: dict[str, str] = {
    "v1": (
        "Ты — классификатор документов. "
        "Определи тип документа по первым фрагментам текста. "
        "Допустимые типы: price_list, specification, technical_document, "
        "resume, other. "
        "Верни JSON строго по схеме, без пояснений.\n\n"
        "Подсказки:\n"
        "- price_list — прайс-лист: список товаров с ценами.\n"
        "- specification — спецификация: описание одного изделия "
        "с характеристиками (память, процессор, цена).\n"
        "- technical_document — техническая документация: разделы, "
        "требования, обозначения (ГОСТ, ТУ).\n"
        "- resume — резюме: данные о человеке, навыки, опыт, образование.\n"
        "- other — всё остальное.\n"
        "Если не уверен — верни other."
    ),
}

# Активная версия классификации
CLASSIFY_VERSION = "v1"


# --- Извлечение данных по схеме --------------------------------------------

EXTRACT: dict[str, str] = {
    "v1": (
        "Ты — ассистент по извлечению структурированных данных из документов. "
        "Извлеки данные строго по JSON Schema, которую тебе передали.\n\n"
        "ПРАВИЛА:\n"
        "1. Извлекай ТОЛЬКО то, что явно есть в тексте. "
        "Если значения нет — оставь пустую строку \"\" или пустой список []. "
        "НЕ ВЫДУМЫВАЙ даты и другие значения.\n"
        "2. Ничего НЕ ВЫДУМЫВАЙ. Если не уверен — оставь пустым.\n"
        "3. Значения копируй КАК В ДОКУМЕНТЕ: с единицами измерения "
        "и валютой. НЕ пересчитывай и не переформатируй.\n"
        "4. Перечисли ВСЕ позиции списков. НЕ СОКРАЩАЙ.\n"
        "5. ВНУТРИ КАЖДОЙ ПОЗИЦИИ списка заполняй ВСЕ поля, которые "
        "есть в схеме этой позиции.\n"
               "6. Не добавляй поля, которых нет в схеме.\n"
        "7. НЕ используй Markdown и символы форматирования "
        "(!, *, $, %, &, #, •, -, —, {}, [], /) в начале или внутри "
        "значений. Пиши только сам текст.\n"
        "8. ВСЕГДА заполняй поле description — краткое описание "
        "содержания документа (1–2 предложения). Если в документе "
        "есть цель, назначение или аннотация — используй их. "
        "Если нет — опиши своими словами, что это за документ.\n\n"
        ),
}

# Активная версия извлечения
EXTRACT_VERSION = "v1"


# --- Извлечение при ремонте (после ошибки валидации) ----------------------

REPAIR: dict[str, str] = {
    "v1": (
        "Предыдущий ответ модели не прошёл валидацию по схеме. "
        "Исправь ошибку и верни корректный JSON.\n\n"
        "Ошибка валидации:\n{error_text}\n\n"
        "ПРАВИЛА остаются те же: извлекай только то, что есть в тексте, "
        "значения копируй как в документе, ничего не выдумывай. "
        "Верни ТОЛЬКО JSON."
    ),
}

REPAIR_VERSION = "v1"


# --- Утилиты ----------------------------------------------------------------

def get_classify_prompt(version: str | None = None) -> str:
    """Возвращает промпт классификации по версии."""
    version = version or CLASSIFY_VERSION
    if version not in CLASSIFY:
        raise KeyError(
            f"Неизвестная версия CLASSIFY: {version}. "
            f"Доступны: {list(CLASSIFY.keys())}"
        )
    return CLASSIFY[version]


def get_extract_prompt(version: str | None = None) -> str:
    """Возвращает промпт извлечения по версии."""
    version = version or EXTRACT_VERSION
    if version not in EXTRACT:
        raise KeyError(
            f"Неизвестная версия EXTRACT: {version}. "
            f"Доступны: {list(EXTRACT.keys())}"
        )
    return EXTRACT[version]


def get_repair_prompt(error_text: str, version: str | None = None) -> str:
    """Возвращает промпт ремонта с подставленной ошибкой."""
    version = version or REPAIR_VERSION
    if version not in REPAIR:
        raise KeyError(
            f"Неизвестная версия REPAIR: {version}. "
            f"Доступны: {list(REPAIR.keys())}"
        )
    return REPAIR[version].format(error_text=error_text)